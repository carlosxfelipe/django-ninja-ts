"""OpenAPI 3.x -> TypeScript generator.

This module is framework-agnostic: it only consumes an OpenAPI document (a plain dict),
so it has no Django imports and can be unit-tested (or reused) in isolation.
"""

from __future__ import annotations

import json
import re
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ninja_ts import runtime

HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")

GENERATED_MARKER = "Auto-generated by django-ninja-ts. Do not edit by hand."
MANAGED_DIR_MARKER = "This directory is managed by django-ninja-ts codegen"
DIR_NOTE = (
    "This directory is managed by django-ninja-ts codegen "
    "(unchanged files skipped, stale generated .ts files removed)."
)

_SHARED_SLUG = "_shared"
_DEFAULT_SLUG = "default"
_SCHEMA_REF_PREFIX = "#/components/schemas/"
_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_INVALID_IDENT_CHARS = re.compile(r"[^A-Za-z0-9_$]+")
_NON_SLUG_CHARS = re.compile(r"[^a-z0-9]+")
_VERSION_OR_API_PREFIX = re.compile(r"^(?:api|v\d+(?:[a-z0-9._-]*)?)$", re.IGNORECASE)
_PATH_PARAM = re.compile(r"\{([^}]+)\}")

# Names that generated schema types must never shadow (TS built-ins + our runtime exports).
_RESERVED_TYPE_NAMES = frozenset(
    {
        "any",
        "unknown",
        "never",
        "void",
        "null",
        "undefined",
        "object",
        "string",
        "number",
        "boolean",
        "symbol",
        "bigint",
        "Array",
        "Record",
        "Partial",
        "Promise",
        "Date",
        "Blob",
        "File",
        "FormData",
        "Headers",
        "Response",
        "Request",
        "URLSearchParams",
        "ReadableStream",
        "Error",
        *runtime.EXPORTED_NAMES,
    }
)

# Request body media types, in order of preference, mapped to the runtime body encoding.
_BODY_MEDIA_TYPES = (
    ("application/json", "json"),
    ("multipart/form-data", "multipart"),
    ("application/x-www-form-urlencoded", "form"),
)


@dataclass
class _Route:
    key: str
    method: str
    path: str
    module: str
    summary: str
    description: str
    deprecated: bool
    params_ts: str
    query_ts: str
    body_ts: str
    response_ts: str
    error_ts: str
    request_ts: str
    body_encoding: str
    direct_refs: frozenset[str] = field(default_factory=frozenset)


def normalize_import_ext(ext: str | None) -> str:
    """Validate and normalize a TypeScript relative import extension."""
    if ext is None or ext == "" or ext.lower() == "none":
        return ""
    lowered = ext.lower()
    if lowered in (".js", "js"):
        return ".js"
    if lowered in (".ts", "ts"):
        return ".ts"
    raise ValueError(
        f"Unsupported import extension {ext!r}. Expected '', 'none', '.js', or '.ts'."
    )


def _strip_jsonc(raw: str) -> str:
    """Strip // line comments, /* */ block comments, and trailing commas from JSONC."""
    out: list[str] = []
    n = len(raw)
    i = 0
    in_string = False
    escaped = False
    while i < n:
        ch = raw[i]
        if in_string:
            out.append(ch)
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
            i += 1
            continue
        if ch == '"':
            in_string = True
            out.append(ch)
            i += 1
        elif ch == "/" and i + 1 < n and raw[i + 1] == "/":
            i += 2
            while i < n and raw[i] != "\n":
                i += 1
        elif ch == "/" and i + 1 < n and raw[i + 1] == "*":
            i += 2
            while i + 1 < n and not (raw[i] == "*" and raw[i + 1] == "/"):
                i += 1
            i += 2
        else:
            out.append(ch)
            i += 1

    no_comments = "".join(out)
    cleaned: list[str] = []
    in_string = False
    escaped = False
    m = len(no_comments)
    for j, ch in enumerate(no_comments):
        if in_string:
            cleaned.append(ch)
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
            cleaned.append(ch)
        elif ch == ",":
            k = j + 1
            while k < m and no_comments[k].isspace():
                k += 1
            if k < m and no_comments[k] in "}]":
                continue
            cleaned.append(ch)
        else:
            cleaned.append(ch)
    return "".join(cleaned)


def _load_json_dict(path: Path, *, jsonc: bool = False) -> dict[str, Any] | None:
    if not path.is_file():
        return None
    try:
        raw = path.read_text(encoding="utf-8")
        data = json.loads(_strip_jsonc(raw) if jsonc else raw)
    except (OSError, ValueError) as _exc:
        return None
    return data if isinstance(data, dict) else None


def detect_ts_import_extension(directory: Path | str) -> str:
    """Detect whether relative imports in ``directory`` should use '', '.js', or '.ts'."""
    cur = Path(directory).resolve()
    while True:
        if (cur / "deno.json").is_file() or (cur / "deno.jsonc").is_file():
            return ".ts"

        tsconfig = _load_json_dict(cur / "tsconfig.json", jsonc=True)
        if tsconfig is not None and isinstance(tsconfig.get("compilerOptions"), dict):
            opts = tsconfig["compilerOptions"]
            mr = str(opts.get("moduleResolution") or "").strip().lower()
            module = str(opts.get("module") or "").strip().lower()
            if opts.get("allowImportingTsExtensions") and opts.get("noEmit"):
                return ".ts"
            if mr in ("node16", "nodenext"):
                return ".js"
            if mr in ("bundler", "node", "node10", "classic"):
                return ""
            if module in ("node16", "nodenext"):
                return ".js"

        pkg = _load_json_dict(cur / "package.json")
        if pkg is not None:
            if pkg.get("type") == "module":
                return ".js"
            return ""

        parent = cur.parent
        if parent == cur:
            break
        cur = parent
    return ""


def resolve_import_ext(ext: str | None, directory: Path | str | None = None) -> str:
    """Resolve ``ext`` (including ``'auto'``) to '', '.js', or '.ts'."""
    if ext is not None and ext.lower() != "auto":
        return normalize_import_ext(ext)
    if directory is None:
        return ""
    return detect_ts_import_extension(directory)


def _slugify(text: str) -> str:
    normalized = unicodedata.normalize("NFKD", text)
    ascii_text = "".join(
        ch for ch in normalized if unicodedata.category(ch) != "Mn"
    ).lower()
    return _NON_SLUG_CHARS.sub("-", ascii_text).strip("-")


def _module_slug(path: str, op: dict[str, Any]) -> str:
    tags = op.get("tags")
    if isinstance(tags, list):
        for tag in tags:
            if isinstance(tag, str):
                slug = _slugify(tag)
                if slug:
                    return slug
    for segment in path.strip("/").split("/"):
        if not segment or segment.startswith("{"):
            continue
        if _VERSION_OR_API_PREFIX.match(segment):
            continue
        slug = _slugify(segment)
        if slug:
            return slug
    return _DEFAULT_SLUG


def _pascal(slug: str) -> str:
    parts = [p for p in re.split(r"[-_]+", slug) if p]
    name = "".join(p[:1].upper() + p[1:] for p in parts) or "Default"
    if name[0].isdigit():
        return f"Api{name}"
    return name


def _literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _prop_name(name: str) -> str:
    return name if _IDENTIFIER.match(name) else _literal(name)


def _wrap(ts: str) -> str:
    """Parenthesize union/intersection types so they compose safely (e.g. in arrays)."""
    return f"({ts})" if (" | " in ts or " & " in ts) else ts


def _union(parts: list[str]) -> str:
    unique = list(dict.fromkeys(parts))
    if not unique:
        return "never"
    if "unknown" in unique:
        return "unknown"
    return " | ".join(_wrap(p) if " & " in p else p for p in unique)


def _doc_lines(text: str | None) -> list[str]:
    if not text:
        return []
    return [line.rstrip().replace("*/", "*\\/") for line in text.strip().splitlines()]


def _jsdoc(lines: list[str], indent: str) -> str:
    lines = [line for line in lines if line is not None]
    if not lines:
        return ""
    body = "".join(f"{indent} * {line}".rstrip() + "\n" for line in lines)
    return f"{indent}/**\n{body}{indent} */\n"


class TypeScriptGenerator:
    """Turns an OpenAPI document into TypeScript declarations and a zero-dependency SDK.

    ``responses_include_all_fields``: Pydantic serializes every field of a response model, so
    for schemas used *only* in responses all properties are typed as present (``field: T``).
    Disable it when routes use ``exclude_none`` / ``exclude_unset`` / ``exclude_defaults``
    (the Django Ninja integration detects this automatically).
    """

    def __init__(
        self, openapi: dict[str, Any], *, responses_include_all_fields: bool = True
    ) -> None:
        self.openapi = openapi
        self.responses_include_all_fields = responses_include_all_fields
        self.schemas: dict[str, Any] = (openapi.get("components") or {}).get(
            "schemas"
        ) or {}
        self._active_ref_sink: set[str] | None = None
        self._names = self._assign_names()
        self._response_only = self._response_only_schemas()

    # ------------------------------------------------------------------ public API

    def generate_sdk(self, *, import_ext: str = "") -> dict[str, str]:
        """Modular TypeScript SDK split into ``index.ts``, ``runtime.ts``, ``types/``, and ``endpoints/``."""
        return self._render_sdk(import_ext=normalize_import_ext(import_ext))

    # ------------------------------------------------------------------ naming

    def _assign_names(self) -> dict[str, str]:
        used = set(_RESERVED_TYPE_NAMES) | self._module_interface_names()
        names: dict[str, str] = {}
        for raw in sorted(self.schemas):
            base = _INVALID_IDENT_CHARS.sub("_", raw).strip("_") or "Model"
            if base[0].isdigit():
                base = f"_{base}"
            name, i = base, 2
            while name in used:
                name, i = f"{base}_{i}", i + 1
            used.add(name)
            names[raw] = name
        return names

    def _ref_name(self, ref: str) -> str:
        if ref.startswith(_SCHEMA_REF_PREFIX):
            raw = ref[len(_SCHEMA_REF_PREFIX) :]
            if raw in self._names:
                if self._active_ref_sink is not None:
                    self._active_ref_sink.add(raw)
                return self._names[raw]
        return "unknown"

    # ------------------------------------------------------------------ $ref helpers

    def _deref(self, node: Any) -> Any:
        """Follow non-schema ``$ref``s (parameters, requestBodies, responses)."""
        seen: set[str] = set()
        while isinstance(node, dict) and isinstance(node.get("$ref"), str):
            ref = node["$ref"]
            if (
                ref.startswith(_SCHEMA_REF_PREFIX)
                or not ref.startswith("#/")
                or ref in seen
            ):
                break
            seen.add(ref)
            target: Any = self.openapi
            for part in ref[2:].split("/"):
                part = part.replace("~1", "/").replace("~0", "~")
                target = target.get(part) if isinstance(target, dict) else None
            if target is None:
                break
            node = target
        return node

    def _collect_refs(self, node: Any, out: set[str]) -> None:
        if isinstance(node, dict):
            ref = node.get("$ref")
            if isinstance(ref, str):
                if ref.startswith(_SCHEMA_REF_PREFIX):
                    out.add(ref[len(_SCHEMA_REF_PREFIX) :])
                else:
                    deref = self._deref(node)
                    if deref is not node:
                        self._collect_refs(deref, out)
            for value in node.values():
                self._collect_refs(value, out)
        elif isinstance(node, list):
            for value in node:
                self._collect_refs(value, out)

    def _closure(self, roots: set[str]) -> set[str]:
        seen: set[str] = set()
        stack = list(roots)
        while stack:
            name = stack.pop()
            if name in seen or name not in self.schemas:
                continue
            seen.add(name)
            refs: set[str] = set()
            self._collect_refs(self.schemas[name], refs)
            stack.extend(refs - seen)
        return seen

    def _response_only_schemas(self) -> set[str]:
        """Schemas reachable only from responses (see ``responses_include_all_fields``).

        Pydantic's JSON schema follows validation semantics (defaulted fields are not
        ``required``), but its serializer always emits every field. For schemas never used as
        input we can therefore type every property as present.
        """
        request_roots: set[str] = set()
        response_roots: set[str] = set()
        for _path, _method, op, item in self._operations():
            self._collect_refs(item.get("parameters"), request_roots)
            self._collect_refs(op.get("parameters"), request_roots)
            self._collect_refs(op.get("requestBody"), request_roots)
            self._collect_refs(op.get("responses"), response_roots)
        return self._closure(response_roots) - self._closure(request_roots)

    def _operations(self):
        for path, item in (self.openapi.get("paths") or {}).items():
            item = self._deref(item) or {}
            for method in HTTP_METHODS:
                op = item.get(method)
                if isinstance(op, dict):
                    yield path, method, op, item

    # ------------------------------------------------------------------ schema -> TS

    def _ts(
        self, schema: Any, response: bool = False, *, strip_null: bool = False
    ) -> str:
        if schema is True or schema is None or schema == {}:
            return "unknown"
        if schema is False:
            return "never"
        if not isinstance(schema, dict):
            return "unknown"
        if "$ref" in schema:
            return self._ref_name(schema["$ref"])
        if "const" in schema:
            return _literal(schema["const"])
        if "enum" in schema:
            values = (
                [v for v in schema["enum"] if v is not None]
                if strip_null
                else list(schema["enum"])
            )
            if not values:
                values = list(schema["enum"])
            ts = _union([_literal(v) for v in values])
            return (
                _union([ts, "null"])
                if schema.get("nullable") is True and not strip_null
                else ts
            )
        for key in ("oneOf", "anyOf"):
            if key in schema:
                parts = [
                    self._ts(s, response, strip_null=strip_null) for s in schema[key]
                ]
                if strip_null:
                    parts = [p for p in parts if p != "null"] or parts
                return _union(parts)
        if "allOf" in schema:
            parts = [
                self._ts(s, response, strip_null=strip_null) for s in schema["allOf"]
            ]
            rest = {k: v for k, v in schema.items() if k != "allOf"}
            if "properties" in rest:
                parts.append(self._object(rest, response))
            parts = list(dict.fromkeys(parts))
            return parts[0] if len(parts) == 1 else " & ".join(_wrap(p) for p in parts)

        type_ = schema.get("type")
        if isinstance(type_, list):
            parts = [
                self._ts({**schema, "type": t}, response, strip_null=strip_null)
                for t in type_
            ]
            if strip_null:
                parts = [p for p in parts if p != "null"] or parts
            return _union(parts)
        ts = self._ts_for_type(schema, type_, response, strip_null=strip_null)
        return (
            _union([ts, "null"])
            if schema.get("nullable") is True and not strip_null
            else ts
        )

    def _ts_for_type(
        self,
        schema: dict[str, Any],
        type_: Any,
        response: bool,
        *,
        strip_null: bool = False,
    ) -> str:
        if type_ == "string":
            return "Blob" if schema.get("format") == "binary" else "string"
        if type_ in ("integer", "number"):
            return "number"
        if type_ == "boolean":
            return "boolean"
        if type_ == "null":
            return "null"
        if type_ == "array":
            if isinstance(schema.get("prefixItems"), list):
                items = ", ".join(
                    self._ts(s, response, strip_null=strip_null)
                    for s in schema["prefixItems"]
                )
                return f"[{items}]"
            return f"{_wrap(self._ts(schema.get('items'), response, strip_null=strip_null))}[]"
        if (
            type_ == "object"
            or "properties" in schema
            or "additionalProperties" in schema
        ):
            return self._object(schema, response)
        return "unknown"

    def _fields(
        self, schema: dict[str, Any], response: bool
    ) -> list[tuple[str, str, bool, list[str]]]:
        """(name, ts_type, required, doc_lines) for each declared property."""
        required = set(schema.get("required") or [])
        all_present = response and self.responses_include_all_fields
        fields = []
        for name, prop in (schema.get("properties") or {}).items():
            prop = prop if isinstance(prop, dict) else {}
            is_required = all_present or name in required
            fields.append(
                (name, self._ts(prop, response), is_required, self._prop_doc(prop))
            )
        return fields

    def _object(self, schema: dict[str, Any], response: bool) -> str:
        fields = self._fields(schema, response)
        extra = schema.get("additionalProperties")
        if not fields:
            if isinstance(extra, dict) and extra:
                return f"Record<string, {self._ts(extra, response)}>"
            if "properties" in schema and extra is not True:
                return "Record<string, never>"  # explicitly empty object
            return "Record<string, unknown>"
        parts = [
            f"{_prop_name(n)}{'' if req else '?'}: {ts}" for n, ts, req, _ in fields
        ]
        if extra is True or (isinstance(extra, dict) and extra):
            parts.append("[key: string]: unknown")
        return "{ " + "; ".join(parts) + " }"

    @staticmethod
    def _prop_doc(prop: dict[str, Any]) -> list[str]:
        lines = _doc_lines(prop.get("description"))
        examples = prop.get("examples")
        if isinstance(examples, list) and examples:
            lines += [f"@example {_literal(e)}" for e in examples]
        elif "example" in prop:
            lines.append(f"@example {_literal(prop['example'])}")
        if "default" in prop:
            lines.append(f"@default {_literal(prop['default'])}")
        format_ = prop.get("format")
        if not format_ and prop.get("type") == "string":
            name = prop.get("title", "").lower()
            if name in ("created_at", "updated_at", "timestamp"):
                format_ = "date-time"
        if format_ and format_ != "binary":
            lines.append(f"@format {format_}")
        if prop.get("deprecated"):
            lines.append("@deprecated")
        return lines

    def _schema_declaration(self, raw: str) -> str:
        schema = self.schemas[raw]
        name = self._names[raw]
        response = raw in self._response_only
        desc = schema.get("description") if isinstance(schema, dict) else None
        if not desc and isinstance(schema, dict):
            title = schema.get("title")
            if title and title != name and title != raw and " " in title:
                desc = title
        doc = _jsdoc(_doc_lines(desc), "")

        is_plain_object = (
            isinstance(schema, dict)
            and bool(schema.get("properties"))
            and not any(
                k in schema for k in ("allOf", "oneOf", "anyOf", "enum", "const")
            )
            and not isinstance(schema.get("type"), list)
            and schema.get("nullable") is not True
        )
        if not is_plain_object:
            return f"{doc}export type {name} = {self._ts(schema, response)};\n"

        lines = [f"{doc}export interface {name} {{\n"]
        for field_name, ts, required, doc_lines in self._fields(schema, response):
            lines.append(_jsdoc(doc_lines, "  "))
            lines.append(
                f"  {_prop_name(field_name)}{'' if required else '?'}: {ts};\n"
            )
        extra = schema.get("additionalProperties")
        if extra is True or (isinstance(extra, dict) and extra):
            lines.append("  [key: string]: unknown;\n")
        lines.append("}\n")
        return "".join(lines)

    # ------------------------------------------------------------------ endpoints

    def _routes(self) -> list[_Route]:
        routes = [
            self._route(path, method, op, item)
            for path, method, op, item in self._operations()
        ]
        return sorted(routes, key=lambda r: r.key)

    def _route(
        self, path: str, method: str, op: dict[str, Any], item: dict[str, Any]
    ) -> _Route:
        # Path-level parameters, overridden by operation-level ones (same name + location).
        merged: dict[tuple[str, str], dict[str, Any]] = {}
        for raw_param in [
            *(item.get("parameters") or []),
            *(op.get("parameters") or []),
        ]:
            param = self._deref(raw_param)
            if isinstance(param, dict) and "name" in param and "in" in param:
                merged[(param["in"], param["name"])] = param

        sink: set[str] = set()
        prev_sink = self._active_ref_sink
        self._active_ref_sink = sink
        try:
            path_fields: dict[str, str] = {}
            query_fields: list[tuple[str, bool]] = []
            header_fields: list[tuple[str, bool]] = []
            for (location, name), param in merged.items():
                required = bool(param.get("required")) or location == "path"
                schema = param.get("schema")
                if schema is None and isinstance(param.get("content"), dict):
                    schema = next(iter(param["content"].values()), {}).get("schema")
                # URL query/path strings cannot represent JSON null; strip it so optional Python
                # parameters like `q: str | None = None` emit `q?: string` rather than `string | null`.
                ts = self._ts(schema, strip_null=location in ("query", "path"))
                if location == "path":
                    path_fields[name] = f"{_prop_name(name)}: {ts}"
                elif location == "query":
                    query_fields.append(
                        (f"{_prop_name(name)}{'' if required else '?'}: {ts}", required)
                    )
                elif location == "header":
                    # Header values travel as strings; keep them compatible with Record<string, string>.
                    header_fields.append(
                        (
                            f"{_prop_name(name)}{'' if required else '?'}: string",
                            required,
                        )
                    )

            for raw_name in _PATH_PARAM.findall(path):
                clean_name = raw_name
                is_catch_all = False
                if raw_name.startswith("path:"):
                    clean_name = raw_name[5:]
                    is_catch_all = True
                elif raw_name.endswith(":path"):
                    clean_name = raw_name[:-5]
                    is_catch_all = True
                elif raw_name.startswith("+") or raw_name.endswith("*"):
                    clean_name = raw_name.lstrip("+").rstrip("*")
                    is_catch_all = True
                elif clean_name.lower() in (
                    "path",
                    "filepath",
                    "file_path",
                ) or clean_name.lower().endswith(("_path", "filepath")):
                    is_catch_all = True

                target_ts = "string | string[]" if is_catch_all else "string"

                if clean_name in path_fields:
                    if is_catch_all and path_fields[clean_name].endswith(": string"):
                        path_fields[clean_name] = (
                            f"{_prop_name(clean_name)}: {target_ts}"
                        )
                elif raw_name in path_fields:
                    val = path_fields.pop(raw_name)
                    ts = (
                        target_ts
                        if (is_catch_all and val.endswith(": string"))
                        else val.split(": ", 1)[1]
                    )
                    path_fields[clean_name] = f"{_prop_name(clean_name)}: {ts}"
                else:
                    path_fields[clean_name] = f"{_prop_name(clean_name)}: {target_ts}"

            params_ts = (
                "{ " + "; ".join(sorted(path_fields.values())) + " }"
                if path_fields
                else "void"
            )
            query_ts = (
                "{ " + "; ".join(f for f, _ in sorted(query_fields)) + " }"
                if query_fields
                else "void"
            )
            headers_ts = (
                "{ " + "; ".join(f for f, _ in sorted(header_fields)) + " }"
                if header_fields
                else ""
            )

            body_ts, body_required, body_encoding = self._request_body(op)
            response_ts = self._response(op)
            has_inputs = bool(
                path_fields or query_fields or header_fields or body_ts != "void"
            )
            error_ts = self._error_response(op, has_inputs=has_inputs)
        finally:
            self._active_ref_sink = prev_sink

        request = []
        request.append(f"params: {params_ts}" if path_fields else "params?: never")
        if query_fields:
            request.append(
                f"query{'' if any(r for _, r in query_fields) else '?'}: {query_ts}"
            )
        else:
            request.append("query?: never")
        if header_fields:
            request.append(
                f"headers{'' if any(r for _, r in header_fields) else '?'}: {headers_ts}"
            )
        if body_ts != "void":
            request.append(f"body{'' if body_required else '?'}: {body_ts}")
        else:
            request.append("body?: never")

        upper = method.upper()
        return _Route(
            key=f"{upper} {path}",
            method=upper,
            path=path,
            module=_module_slug(path, op),
            summary=str(op.get("summary") or ""),
            description=str(op.get("description") or ""),
            deprecated=bool(op.get("deprecated")),
            params_ts=params_ts,
            query_ts=query_ts,
            body_ts=body_ts,
            response_ts=response_ts,
            error_ts=error_ts,
            request_ts="{ " + "; ".join(request) + " }",
            body_encoding=body_encoding,
            direct_refs=frozenset(sink),
        )

    def _request_body(self, op: dict[str, Any]) -> tuple[str, bool, str]:
        body = self._deref(op.get("requestBody"))
        if (
            not isinstance(body, dict)
            or not isinstance(body.get("content"), dict)
            or not body["content"]
        ):
            return "void", False, "json"
        content: dict[str, Any] = body["content"]
        required = bool(body.get("required"))

        for media_type, encoding in _BODY_MEDIA_TYPES:
            if media_type in content:
                ts = self._ts((content[media_type] or {}).get("schema"))
                if encoding == "multipart":
                    ts = f"{_wrap(ts)} | FormData"
                elif encoding == "form":
                    ts = f"{_wrap(ts)} | URLSearchParams"
                return ts, required, encoding
        for media_type, media in content.items():
            if media_type.endswith("+json"):
                return self._ts((media or {}).get("schema")), required, "json"
        return "Blob | ArrayBuffer | string", required, "raw"

    def _content_ts(self, response: Any, *, response_schema: bool = True) -> str:
        if not isinstance(response, dict):
            return "unknown"
        content = response.get("content") if isinstance(response, dict) else None
        if not isinstance(content, dict) or not content:
            return "unknown"
        for media_type, media in content.items():
            if media_type == "application/json" or media_type.endswith("+json"):
                return self._ts((media or {}).get("schema"), response=response_schema)
        if "text/event-stream" in content:
            return "ReadableStream<string>"
        if any(mt.startswith("text/") for mt in content):
            return "string"
        return "Blob"

    def _response(self, op: dict[str, Any]) -> str:
        # Keys may be ints (raw Ninja schema) or strings (JSON-loaded schema).
        responses = {str(k): v for k, v in (op.get("responses") or {}).items()}
        codes = sorted(int(c) for c in responses if c.isdigit() and 200 <= int(c) < 300)
        if codes:
            code = codes[0]
            response = self._deref(responses[str(code)])
        elif "2XX" in responses:
            code, response = 200, self._deref(responses["2XX"])
        else:
            return "unknown"

        if code in (204, 205):
            return "void"
        return self._content_ts(response, response_schema=True)

    def _error_response(self, op: dict[str, Any], *, has_inputs: bool = False) -> str:
        responses = {str(k): v for k, v in (op.get("responses") or {}).items()}
        error_types: list[str] = []
        for k in sorted(
            responses, key=lambda x: (0, int(x)) if x.isdigit() else (1, x)
        ):
            if (k.isdigit() and int(k) >= 400) or k in ("4XX", "5XX", "default"):
                resp = self._deref(responses[k])
                error_types.append(self._content_ts(resp, response_schema=True))

        concrete = [t for t in error_types if t != "unknown"]
        if concrete:
            return _union(concrete)
        if has_inputs:
            return "NinjaHttpError | NinjaValidationError"
        return "NinjaHttpError"

    # ------------------------------------------------------------------ rendering

    def _route_entry(self, r: _Route) -> str:
        doc = _doc_lines(r.summary)
        if r.description and r.description != r.summary:
            doc += _doc_lines(r.description)
        if r.deprecated:
            doc.append("@deprecated")
        lines = [_jsdoc(doc, "  ")]
        lines.append(f"  {_literal(r.key)}: {{\n")
        lines.append(f"    method: {_literal(r.method)};\n")
        lines.append(f"    path: {_literal(r.path)};\n")
        lines.append(f"    params: {r.params_ts};\n")
        lines.append(f"    query: {r.query_ts};\n")
        lines.append(f"    body: {r.body_ts};\n")
        lines.append(f"    response: {r.response_ts};\n")
        lines.append(f"    error: {r.error_ts};\n")
        lines.append(f"    request: {r.request_ts};\n")
        lines.append("  };\n")
        return "".join(lines)

    def _render_body_encodings(self, routes: list[_Route], *, type_name: str) -> str:
        encodings = {
            r.key: r.body_encoding for r in routes if r.body_encoding != "json"
        }
        out = [f"\nconst BODY_ENCODINGS: {type_name} = {{"]
        if encodings:
            out.append("\n")
            for key, encoding in encodings.items():
                out.append(f"  {_literal(key)}: {_literal(encoding)},\n")
        out.append("};\n")
        return "".join(out)

    def _render_sdk(self, *, import_ext: str) -> dict[str, str]:
        routes = self._routes()
        modules: dict[str, list[_Route]] = {}
        for r in routes:
            modules.setdefault(r.module, []).append(r)

        # Render each schema while capturing exact schema-to-schema references.
        schema_decls: dict[str, str] = {}
        schema_deps: dict[str, set[str]] = {}
        for raw in self.schemas:
            deps: set[str] = set()
            prev_sink = self._active_ref_sink
            self._active_ref_sink = deps
            try:
                decl = self._schema_declaration(raw)
            finally:
                self._active_ref_sink = prev_sink
            deps.discard(raw)
            schema_decls[raw] = decl
            schema_deps[raw] = deps

        # Assign each reachable schema to a module if only one module reaches it, else _shared.
        # Unreachable schemas (e.g. Query[...] filter models expanded inline) are omitted.
        module_reach: dict[str, set[str]] = {raw: set() for raw in self.schemas}
        for slug, mod_routes in modules.items():
            roots: set[str] = set().union(*(r.direct_refs for r in mod_routes))
            seen: set[str] = set()
            stack = list(roots)
            while stack:
                cur = stack.pop()
                if cur in seen or cur not in self.schemas:
                    continue
                seen.add(cur)
                module_reach[cur].add(slug)
                stack.extend(schema_deps[cur] - seen)

        schema_owner: dict[str, str] = {}
        owner_schemas: dict[str, list[str]] = {}
        for raw in sorted(self.schemas, key=lambda r: self._names[r]):
            owners = module_reach[raw]
            if not owners:
                continue
            owner = next(iter(owners)) if len(owners) == 1 else _SHARED_SLUG
            schema_owner[raw] = owner
            owner_schemas.setdefault(owner, []).append(raw)

        type_owners = sorted(
            owner_schemas, key=lambda s: (0 if s == _SHARED_SLUG else 1, s)
        )
        mod_slugs = sorted(modules)
        mod_ifaces = self._assign_module_interfaces(mod_slugs)

        files: dict[str, str] = {
            "runtime.ts": self._render_modular_runtime(),
            "index.ts": self._render_modular_index(
                routes=routes,
                type_owners=type_owners,
                mod_slugs=mod_slugs,
                mod_ifaces=mod_ifaces,
                import_ext=import_ext,
            ),
        }
        for owner in type_owners:
            files[f"types/{owner}.ts"] = self._render_modular_types_file(
                owner=owner,
                raws=owner_schemas[owner],
                schema_decls=schema_decls,
                schema_deps=schema_deps,
                schema_owner=schema_owner,
                import_ext=import_ext,
            )
        for slug in mod_slugs:
            files[f"endpoints/{slug}.ts"] = self._render_modular_endpoints_file(
                slug=slug,
                iface_name=mod_ifaces[slug],
                mod_routes=modules[slug],
                schema_owner=schema_owner,
                import_ext=import_ext,
            )
        return files

    @staticmethod
    def _assign_module_interfaces(slugs: list[str]) -> dict[str, str]:
        used = {"NinjaEndpoints"}
        assigned: dict[str, str] = {}
        for slug in sorted(slugs):
            base = f"{_pascal(slug)}Endpoints"
            name, i = base, 2
            while name in used:
                name, i = f"{base}_{i}", i + 1
            used.add(name)
            assigned[slug] = name
        return assigned

    def _module_interface_names(self) -> set[str]:
        slugs = sorted(
            {_module_slug(path, op) for path, _method, op, _item in self._operations()}
        )
        return set(self._assign_module_interfaces(slugs).values())

    def _api_label(self) -> str:
        info = self.openapi.get("info") or {}
        if not info.get("title"):
            return ""
        version = f" ({info['version']})" if info.get("version") else ""
        return f"{info['title']}{version}"

    def _render_modular_runtime(self) -> str:
        lines = [GENERATED_MARKER, DIR_NOTE]
        label = self._api_label()
        if label:
            lines.append(f"API: {label}")
        info = self.openapi.get("info") or {}
        lines += _doc_lines(info.get("description"))
        return f"{_jsdoc(lines, '')}\n{runtime.MODULAR_RUNTIME.lstrip()}"

    def _render_modular_types_file(
        self,
        *,
        owner: str,
        raws: list[str],
        schema_decls: dict[str, str],
        schema_deps: dict[str, set[str]],
        schema_owner: dict[str, str],
        import_ext: str,
    ) -> str:
        label = self._api_label()
        title_line = f"API: {label} — Types ({owner})" if label else f"Types ({owner})"
        out = [_jsdoc([GENERATED_MARKER, title_line], ""), "\n"]

        imports_by_owner: dict[str, set[str]] = {}
        for raw in raws:
            for dep in schema_deps[raw]:
                dep_owner = schema_owner[dep]
                if dep_owner != owner:
                    imports_by_owner.setdefault(dep_owner, set()).add(self._names[dep])

        if imports_by_owner:
            for dep_owner in sorted(
                imports_by_owner, key=lambda s: (0 if s == _SHARED_SLUG else 1, s)
            ):
                names = ", ".join(sorted(imports_by_owner[dep_owner]))
                out.append(
                    f'import type {{ {names} }} from "./{dep_owner}{import_ext}";\n'
                )
            out.append("\n")

        for i, raw in enumerate(raws):
            if i > 0:
                out.append("\n")
            out.append(schema_decls[raw])
        return "".join(out)

    def _render_modular_endpoints_file(
        self,
        *,
        slug: str,
        iface_name: str,
        mod_routes: list[_Route],
        schema_owner: dict[str, str],
        import_ext: str,
    ) -> str:
        label = self._api_label()
        title_line = (
            f"API: {label} — Endpoints ({slug})" if label else f"Endpoints ({slug})"
        )
        out = [_jsdoc([GENERATED_MARKER, title_line], ""), "\n"]

        runtime_types = sorted(
            {
                name
                for r in mod_routes
                for name in ("NinjaHttpError", "NinjaValidationError")
                if re.search(rf"\b{name}\b", r.error_ts)
            }
        )
        imports_by_owner: dict[str, set[str]] = {}
        for r in mod_routes:
            for raw in r.direct_refs:
                owner = schema_owner[raw]
                imports_by_owner.setdefault(owner, set()).add(self._names[raw])

        if runtime_types:
            names = ", ".join(runtime_types)
            out.append(f'import type {{ {names} }} from "../runtime{import_ext}";\n')
        if imports_by_owner:
            for owner in sorted(
                imports_by_owner, key=lambda s: (0 if s == _SHARED_SLUG else 1, s)
            ):
                names = ", ".join(sorted(imports_by_owner[owner]))
                out.append(
                    f'import type {{ {names} }} from "../types/{owner}{import_ext}";\n'
                )
        if runtime_types or imports_by_owner:
            out.append("\n")

        out.append(f"export interface {iface_name} {{\n")
        for r in mod_routes:
            out.append(self._route_entry(r))
        out.append("}\n")
        return "".join(out)

    def _render_modular_index(
        self,
        *,
        routes: list[_Route],
        type_owners: list[str],
        mod_slugs: list[str],
        mod_ifaces: dict[str, str],
        import_ext: str,
    ) -> str:
        out = [self._header(), "\n"]

        for slug in mod_slugs:
            out.append(
                f'import type {{ {mod_ifaces[slug]} }} from "./endpoints/{slug}{import_ext}";\n'
            )
        out.append(
            f'import {{ createNinjaClientFor, isNinjaApiError }} from "./runtime{import_ext}";\n'
        )
        out.append(
            "import type {\n"
            "  BodyEncodingMap,\n"
            "  NinjaApiError,\n"
            "  NinjaClientFor,\n"
            "  NinjaClientOptions,\n"
            "  RequestOptionsFor,\n"
            f'}} from "./runtime{import_ext}";\n\n'
        )
        out.append(
            "export {\n"
            "  DEFAULT_RETRY_METHODS,\n"
            "  NinjaApiError,\n"
            "  createNinjaClientFor,\n"
            "  isAbortError,\n"
            "  isNinjaApiError,\n"
            "  parseNinjaError,\n"
            f'}} from "./runtime{import_ext}";\n'
        )
        out.append(
            "export type {\n"
            "  BaseRequestOptions,\n"
            "  BodyEncoding,\n"
            "  BodyEncodingMap,\n"
            "  NextFetchRequestConfig,\n"
            "  NinjaClientFor,\n"
            "  NinjaClientOptions,\n"
            "  NinjaEndpointDef,\n"
            "  NinjaErrorDetails,\n"
            "  NinjaErrorKind,\n"
            "  NinjaHttpError,\n"
            "  NinjaQueryKeyArgs,\n"
            "  NinjaQueryOptions,\n"
            "  NinjaRequestConfig,\n"
            "  NinjaRequestInit,\n"
            "  NinjaRetryConfig,\n"
            "  NinjaValidationError,\n"
            "  NinjaValidationErrorItem,\n"
            "  RequestContext,\n"
            "  RequestOptionsFor,\n"
            f'}} from "./runtime{import_ext}";\n'
        )
        for owner in type_owners:
            out.append(f'export type * from "./types/{owner}{import_ext}";\n')
        for slug in mod_slugs:
            out.append(f'export type * from "./endpoints/{slug}{import_ext}";\n')

        out.append("\n")
        if mod_slugs:
            extends = ", ".join(mod_ifaces[slug] for slug in mod_slugs)
            out.append(f"export interface NinjaEndpoints extends {extends} {{}}\n\n")
        else:
            out.append("export interface NinjaEndpoints {}\n\n")

        out.append(runtime.ENDPOINT_BINDING_TYPES)
        out.append(self._render_body_encodings(routes, type_name="BodyEncodingMap"))
        out.append(
            "\n"
            "export function isEndpointError<K extends EndpointKey>(\n"
            "  error: unknown,\n"
            "  endpoint: K,\n"
            "): error is NinjaApiError<ResponseError<K>> {\n"
            "  return isNinjaApiError(error) && error.endpoint === endpoint;\n"
            "}\n\n"
            "export function createNinjaClient(\n"
            '  baseUrl = "",\n'
            "  clientOptions: NinjaClientOptions = {},\n"
            "): NinjaClient {\n"
            "  return createNinjaClientFor<NinjaEndpoints>(baseUrl, clientOptions, BODY_ENCODINGS);\n"
            "}\n"
        )
        return "".join(out)

    def _header(self) -> str:
        lines = [GENERATED_MARKER, DIR_NOTE]
        label = self._api_label()
        if label:
            lines.append(f"API: {label}")
        info = self.openapi.get("info") or {}
        lines += _doc_lines(info.get("description"))
        return _jsdoc(lines, "")


def generate_sdk(
    openapi: dict[str, Any], *, import_ext: str = "", **options: Any
) -> dict[str, str]:
    """Generate a modular TypeScript SDK (relative path -> content)."""
    return TypeScriptGenerator(openapi, **options).generate_sdk(import_ext=import_ext)
